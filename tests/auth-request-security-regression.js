// Isolated database only. Never run against a hosted database.
if (!/^postgres(?:ql)?:\/\/[^/]*@(localhost|127\.0\.0\.1):/.test(process.env.DATABASE_URL || '')) throw new Error('Isolated DB required');
const assert = require('node:assert/strict');
const path = require('path');
const jiti = require('jiti')(__filename, {alias: {'@': path.resolve(__dirname, '../src')}});
const {NextRequest, NextResponse} = require('next/server');
const {prisma} = jiti('../src/server/db/prisma');
const {readBoundedText, consumeAuthBudget, protectAuthRequest} = jiti('../src/server/services/auth-request-security');
(async () => {
 const id = 'isolated-rate-' + Date.now();
 const result = await Promise.all(Array.from({length: 25}, () => consumeAuthBudget('race', id, 10, 900000)));
 assert.equal(result.filter(Boolean).length, 10, 'atomic cross-instance budget');
 assert.equal(await consumeAuthBudget('race', id+'-other', 10, 900000), true);
 const req = (body,headers={}) => new NextRequest('http://localhost:3000/api/auth/login', {method:'POST',body,headers:{'content-type':'application/json','x-forwarded-for':'192.0.2.45',...headers}});
 const wrapped=protectAuthRequest(async()=>NextResponse.json({success:true}),{scope:id,identityLimit:2});
 assert.equal((await wrapped(req('{}', {origin:'https://evil.invalid'}))).status,403);
 assert.equal((await wrapped(req('{}', {origin:'http://localhost:3000'}))).status,200);
 assert.equal((await wrapped(req('{}'))).status,200);
 assert.equal((await wrapped(req('[]'))).status,400);
 assert.equal((await wrapped(req('{'))).status,400);
 assert.equal((await wrapped(req('x'.repeat(65537)))).status,413);
 const input=JSON.stringify({email:'Rate@Example.test'});
 assert.equal((await wrapped(req(input))).status,200);
 assert.equal((await wrapped(req(input))).status,200);
 assert.equal((await wrapped(req(input))).status,429);
 const generic={success:true,message:'If this email has an account, a reset link is on its way.'};
 const forgot=protectAuthRequest(async()=>NextResponse.json(generic),{scope:id+'forgot',identityLimit:1,generic});
 assert.deepEqual(await (await forgot(req(input))).json(),generic);
 assert.deepEqual(await (await forgot(req(input))).json(),generic);
 const bytes = new TextEncoder().encode('é'.repeat(32769));
 await assert.rejects(readBoundedText(new Request('http://localhost',{method:'POST',body:bytes})),e=>e.status===413);
 assert.equal(await readBoundedText(req('{"a":1}')),'{"a":1}');
 const expiredKey = require('crypto').createHmac('sha256',process.env.JWT_SECRET).update('auth-budget-v1\0expire\0'+id).digest('hex');
 await prisma.securityRateLimit.create({data:{key:expiredKey,hits:10,expiresAt:new Date(Date.now()-1000)}});
 assert.equal(await consumeAuthBudget('expire',id,10,900000),true,'expired budgets reset');
 const stored = await prisma.securityRateLimit.findUnique({where:{key:expiredKey}});
 assert.equal(stored.hits,1);
 assert.equal(stored.key.includes(id),false);
 const previous=process.env.VERCEL;process.env.VERCEL='1';
 const trusted=protectAuthRequest(async()=>NextResponse.json({success:true}),{scope:id+'trusted',ipLimit:1});
 assert.equal((await trusted(req('{}',{'x-vercel-forwarded-for':'192.0.2.81','x-forwarded-for':'203.0.113.1'}))).status,200);
 assert.equal((await trusted(req('{}',{'x-vercel-forwarded-for':'192.0.2.81','x-forwarded-for':'203.0.113.2'}))).status,429,'spoofing XFF cannot change trusted Vercel budget');
 if(previous===undefined)delete process.env.VERCEL;else process.env.VERCEL=previous;
 const {POST:login}=jiti('../src/app/api/auth/login/route');
 assert.equal((await login(req(JSON.stringify({email:'unknown@example.test',password:'not-a-real-password'}),{origin:'https://evil.invalid'}))).status,403);
 const invalid=await login(req(JSON.stringify({email:'unknown@example.test',password:'not-a-real-password'})));
 assert.equal(invalid.status,401);assert.deepEqual(Object.keys(await invalid.json()).sort(),['error','success']);
 const {validateNewPassword}=jiti('../src/server/services/password-policy');
 assert.equal(validateNewPassword('a1'+'é'.repeat(36))!==null,true);
 assert.equal(validateNewPassword('ValidPassw0rd'),null);
 const {safeRoute}=jiti('../src/server/services/safe-route');
 const failed=await safeRoute(async()=>{throw new Error('private-provider-error-must-not-escape')})();
 assert.equal(failed.status,500);assert.equal((await failed.text()).includes('private-provider'),false);
 const known=NextResponse.json({success:true,data:[1,2]},{status:201});
 assert.equal(await safeRoute(async()=>known)(),known);
 console.log('PASS auth request security: atomic budget, origins, no-Origin, caps, JSON, generic reset responses');
})().then(()=>prisma.$disconnect()).catch(async e=>{console.error(e);await prisma.$disconnect();process.exitCode=1});
